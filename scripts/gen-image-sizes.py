"""Regenerate src/lib/data/wp-image-sizes.ts from the files in public/images/wp.

Run after adding images:  python3 scripts/gen-image-sizes.py   (needs Pillow)
"""
import os
import re

from PIL import Image

ROOT = "public/images/wp"
out = {}
for dp, _, files in os.walk(ROOT):
    for f in files:
        p = os.path.join(dp, f)
        rel = os.path.relpath(p, ROOT)
        if f.endswith(".svg"):
            s = open(p, errors="ignore").read(4000)
            w = re.search(r'width="([\d.]+)', s)
            h = re.search(r'height="([\d.]+)', s)
            vb = re.search(r'viewBox="[\d.\- ]*?([\d.]+) ([\d.]+)"', s)
            W = float(w.group(1)) if w else (float(vb.group(1)) if vb else 100)
            H = float(h.group(1)) if h else (float(vb.group(2)) if vb else 100)
            out[rel] = (round(W), round(H))
        else:
            out[rel] = Image.open(p).size

lines = [
    "// Generated by scripts/gen-image-sizes.py — intrinsic sizes of public/images/wp for next/image.",
    "export const wpImageSizes: Record<string, [number, number]> = {",
]
lines += [f'  "{k}": [{v[0]}, {v[1]}],' for k, v in sorted(out.items())]
lines.append("};")
open("src/lib/data/wp-image-sizes.ts", "w").write("\n".join(lines) + "\n")
print(f"{len(out)} images")
